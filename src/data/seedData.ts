// Helper to calculate relative date string YYYY-MM-DD from today
function getRelDate(daysFromToday: number): string {
  // Use today: 2026-10-23
  const d = new Date('2026-10-23T00:00:00Z');
  d.setUTCDate(d.getUTCDate() + daysFromToday);
  return d.toISOString().slice(0, 10);
}

